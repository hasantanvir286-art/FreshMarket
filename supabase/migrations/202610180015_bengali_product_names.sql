-- Optional customer-facing Bengali product names.
alter table public.products add column if not exists name_bn text;

update public.products
set name_bn = case slug
  when 'bd-bananas' then 'কলা'
  when 'bd-mangoes' then 'মৌসুমি আম'
  when 'bd-guava' then 'পেয়ারা'
  when 'bd-papaya' then 'পেঁপে'
  when 'bd-pineapple' then 'আনারস'
  when 'bd-green-coconut' then 'ডাব'
  when 'bd-sweet-lime' then 'মিষ্টি লেবু'
  when 'bd-potatoes' then 'আলু'
  when 'bd-red-onions' then 'লাল পেঁয়াজ'
  when 'bd-tomatoes' then 'টমেটো'
  when 'bd-green-chillies' then 'কাঁচা মরিচ'
  when 'bd-eggplant' then 'বেগুন'
  when 'bd-cauliflower' then 'ফুলকপি'
  when 'bd-spinach' then 'পালং শাক'
  when 'bd-cucumber' then 'শসা'
  when 'bd-carrots' then 'গাজর'
  when 'bd-rohu' then 'রুই মাছ'
  when 'bd-hilsa' then 'ইলিশ মাছ'
  when 'bd-tilapia' then 'তেলাপিয়া মাছ'
  when 'bd-chicken' then 'তাজা মুরগি'
  when 'bd-beef' then 'গরুর মাংস'
  when 'bd-eggs' then 'খামারের ডিম'
  when 'bd-milk' then 'পাস্তুরিত দুধ'
  when 'bd-yogurt' then 'টক দই'
  when 'bd-butter' then 'মাখন'
  when 'bd-white-bread' then 'সাদা পাউরুটি'
  when 'bd-paratha' then 'হিমায়িত পরোটা'
  when 'bd-miniket-rice' then 'মিনিকেট চাল'
  when 'bd-najirshail-rice' then 'নাজিরশাইল চাল'
  when 'bd-chinigura-rice' then 'চিনিগুঁড়া সুগন্ধি চাল'
  when 'bd-atta' then 'আটা'
  when 'bd-muri' then 'মুড়ি'
  when 'bd-masoor-dal' then 'মসুর ডাল'
  when 'bd-mung-dal' then 'মুগ ডাল'
  when 'bd-chickpeas' then 'ছোলা'
  when 'bd-soybean-oil' then 'সয়াবিন তেল'
  when 'bd-sugar' then 'চিনি'
  when 'bd-salt' then 'আয়োডিনযুক্ত লবণ'
  when 'bd-turmeric' then 'হলুদ গুঁড়া'
  when 'bd-red-chilli-powder' then 'মরিচ গুঁড়া'
  when 'bd-tea' then 'বাংলাদেশি চা'
  when 'bd-chanachur' then 'চানাচুর'
  else name_bn
end
where name_bn is null and slug like 'bd-%';
